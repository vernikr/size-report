import fs from 'node:fs';

/* Оформление отчёта — обычные `.css` рядом с кодом, а не строки внутри модулей:
 * то же правило, что и у программы страницы (`src/page/app.js`), — исходник видит
 * редактор, а не только шаблонная строка. Читаются они с диска относительно
 * своего места, поэтому работают и у того, кто поставил пакет.
 *
 * Наборов три, и у каждого своя роль:
 *
 *   1. `table.css` — **общая часть таблицы**: геометрия клеток, липкие шапка и
 *      колонка коммита, подпись коммита, цвета дельт. Её берут оба вывода, поэтому
 *      расхождению в оформлении самой таблицы взяться неоткуда. Файл — дословный
 *      текст этой части, без шапки: он попадает в артефакт побайтово, а артефакт
 *      заморожен эталоном паритета, и любая добавленная строка меняла бы
 *      зафиксированный вывод проекта-потребителя.
 *   2. `artifact.css` — оформление статического артефакта **сверх таблицы**: холст,
 *      заголовок, примечание.
 *   3. `page/app.css` — оформление страницы **сверх таблицы**: холст, панель
 *      выбора, легенда, состояния пустоты и адаптации под узкое окно.
 *
 * Соглашение о цвете дельт задано один раз — в `table.css`: `.up` зелёный, `.down`
 * красный (рост — «больше логики», а не тревога). Артефакт заморожен побайтово, и
 * менять его цвета нельзя, не пересняв эталон; страница следует тому же
 * соглашению, потому что два отчёта одной истории не могут показывать рост
 * разными цветами. Смена соглашения — две строки в `table.css` и пересъёмка
 * эталона артефакта; отдельного места у цвета дельт нет намеренно.
 *
 * Путь у `readCss` — от каталога `src/`: так его видит движок, где бы он ни лежал.
 */

export const TABLE_CSS = readCss('./table.css');
export const ARTIFACT_CSS = readCss('./artifact.css');
export const PAGE_CSS = readCss('./page/app.css');

function readCss(name) {
  return fs.readFileSync(new URL(name, import.meta.url), 'utf8').trim();
}

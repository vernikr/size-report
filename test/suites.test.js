/* Сторож разделения набора на быстрый и полный прогон (`tools/suites.js`).
 *
 * Класс дефекта тут свой: разделение стареет молча. Файл, которого нет в
 * объявлении, попадает в полный прогон — и это правильно, но «почему он в полном»
 * остаётся догадкой; быстрым файл может стать «заодно», и никто не заметит, что
 * быстрый прогон перестал быть быстрым; число проверок в прогоне и в документе
 * расходятся так же тихо, как расходились числа проверок в `README.md` до сторожа
 * документации.
 *
 * Что стережёт проверка: у каждого файла набора — своё место (быстрый явно, полный с
 * названной причиной), у быстрого файла — причина и снимок стоимости в пределах
 * потолка, сумма заявленных стоимостей укладывается в цель быстрого прогона, и
 * быстрый прогон остаётся частью набора, а не вторым набором. Числа прогонов в
 * документации — дело сторожа документации (`test/docs-numbers.test.js`): одно
 * обещание живёт в одном доме, иначе два сторожа начнут спорить, кто прав.
 *
 * **Чего проверка не берёт, и это сказано, а не спрятано:** верность снимка
 * стоимости. Снимок — измерение в названном окне, и совпадение снимка с сегодняшней
 * машиной проверяет не тест, а прогон: `tools/run-tests.js` мерит каждый файл своим
 * запуском и печатает замер рядом с объявлением, а за бюджет вдвое валится — то есть
 * дорогой файл, уехавший в быстрый, видно прогоном, а не объявлением. Здесь же
 * стерегутся форма, полнота и границы объявления.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { BUDGET, FAST, LIMIT, MEASURED, ROOT, SLOW, checksIn, testFiles } from '../tools/suites.js';

const files = testFiles();
const fast = FAST.map((e) => e.file);
const slow = SLOW.map((e) => e.file);

function duplicated(list) {
  return list.filter((f, i) => list.indexOf(f) !== i);
}

function written(file) {
  return path.relative(ROOT, file).split(path.sep).join('/');
}

test('каждый файл набора классифицирован: быстрый — явно, полный — с причиной', () => {
  assert.deepEqual(duplicated(fast), [], 'в быстром прогоне файл назван дважды');
  assert.deepEqual(duplicated(slow), [], 'причина для полного прогона названа дважды');
  assert.deepEqual(fast.filter((f) => slow.indexOf(f) >= 0), [],
    'файл назван и быстрым, и полным: он не может быть в двух прогонах сразу');
  assert.deepEqual(fast.filter((f) => files.indexOf(f) < 0), [],
    'быстрым назван файл, которого в наборе нет');
  assert.deepEqual(slow.filter((f) => files.indexOf(f) < 0), [],
    'причина названа для файла, которого в наборе нет');

  // Файл, которого нет в быстром списке, идёт в полный — это умолчание, и оно
  // хорошее: новое не может тихо уехать в быстрый. Но тогда причина обязана быть у
  // каждого такого файла: иначе «почему он в полном» никто не назвал.
  assert.deepEqual(files.filter((f) => fast.indexOf(f) < 0 && slow.indexOf(f) < 0).map(written), [],
    'в полном прогоне файл без названной причины — допишите её в SLOW (`tools/suites.js`)'
      + ' или переведите файл в быстрый с причиной и снимком стоимости');
});

test('у быстрого файла названы причина и стоимость, и она в пределах потолка', () => {
  FAST.forEach((entry) => {
    assert.ok(entry.why !== undefined && entry.why.length > 30,
      'быстрый файл без причины (' + entry.file + '): почему он здесь, а не в полном прогоне?');
    assert.ok(typeof entry.cost === 'number' && entry.cost > 0,
      'у быстрого файла нет снимка стоимости: ' + entry.file);
    assert.ok(entry.cost <= LIMIT, entry.file + ' объявлен быстрым со стоимостью '
      + entry.cost + ' с при потолке ' + LIMIT + ' с — цена говорит, что его место в полном прогоне');
  });
  SLOW.forEach((entry) => {
    assert.ok(entry.why !== undefined && entry.why.length > 30,
      'у дорогого файла не названа причина, почему он в полном прогоне: ' + entry.file);
    assert.ok(typeof entry.cost === 'number' && entry.cost > 0,
      'у дорогого файла нет снимка стоимости: ' + entry.file);
  });
  assert.ok(/\d{4}-\d{2}-\d{2}/.test(MEASURED),
    'у снимка стоимостей не названо окно замера — числа разных окон несравнимы');

  // Снимок складывать нельзя: файлы идут параллельно, а цель — про время прогона, а
  // не про сумму одиночных запусков (и это же значит, что верность снимка проверяет
  // замер прогона, а не арифметика здесь). Проверяется то, что обещает само
  // объявление: ни один быстрый файл не дороже цели прогона целиком.
  const worst = FAST.reduce((max, entry) => Math.max(max, entry.cost), 0);
  assert.ok(worst <= BUDGET.fast, 'самый дорогой быстрый файл стоит ' + worst
    + ' с — больше цели всего быстрого прогона (' + BUDGET.fast + ' с)');
});

test('быстрый прогон — часть набора, и цели прогонов различимы', () => {
  const total = files.reduce((sum, f) => sum + checksIn(f), 0);
  const inFast = fast.reduce((sum, f) => sum + checksIn(f), 0);
  assert.ok(inFast > 0, 'быстрый прогон пуст: тогда его незачем звать');
  assert.ok(inFast < total, 'быстрый прогон равен полному (' + inFast + ' из ' + total
    + ') — разделения нет, а цель у него строже');
  assert.ok(BUDGET.fast < BUDGET.full, 'цель быстрого прогона (≤ ' + BUDGET.fast
    + ' с) не строже цели полного (≤ ' + BUDGET.full + ' с)');
  // Каждый файл набора учтён в подсчёте ровно один раз: полнота классификации выше
  // уже проверена, а здесь важно, что быстрый прогон не перечислил один файл дважды
  // и не потерял проверки при подсчёте.
  assert.equal(inFast, FAST.reduce((sum, entry) => sum + checksIn(entry.file), 0),
    'счёт проверок быстрого прогона не сходится с его файлами');
});
